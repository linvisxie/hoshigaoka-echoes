def write(sid, title, lines, background='bg_env_corridor_dusk', flags=()):
    nodes = []
    for i, (name, text) in enumerate(lines):
        speaker, character = CAST[name]
        node={'id': str(i), 'speaker': speaker, 'character': character, 'text': text}
        if character=='amamiya_mio':
            node['emotion']='serious'
            if any(x in text for x in ['谢谢','一起','欢迎','名字']):node['emotion']='smile'
            if any(x in text for x in ['没事','守住','相信','不能']):node['emotion']='determined'
            if any(x in text for x in ['疲','累','疼']):node['emotion']='hurt'
        nodes.append(node)
    data = {'schemaVersion':'1.0.0', 'domain':'story', 'storyId':sid, 'chapterId':'ch1',
            'title':title, 'background':background, 'music':'observation_club' if sid=='ch1_1_5_after' else 'unheard_memory',
            'authorship':'Original project dialogue based on V2.1.4 chapter events; 2026-10-10',
            'completionFlags':list(flags), 'nodes':nodes}
    (ROOT/'data/story'/f'{sid}.json').write_text(json.dumps(data,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')

